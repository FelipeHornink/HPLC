// setting: value of hplc.language ("auto" | "en" | "pt-BR");
// displayLanguage: vscode.env.language (e.g. "en", "pt-br").
function resolveLanguage(setting, displayLanguage) {
  if (setting === 'en' || setting === 'pt-BR') return setting;
  return String(displayLanguage || '').toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
}

function vscodeLanguage() {
  try {
    const vscode = require('vscode');
    const setting = vscode.workspace?.getConfiguration?.('hplc')?.get?.('language');
    return resolveLanguage(setting, vscode.env?.language);
  } catch (_) {
    return 'en';
  }
}

let resolver = vscodeLanguage;

// Tests (or hosts without VS Code) inject a function returning
// 'en' | 'pt-BR' | 'auto'-style settings; pass undefined to restore the default.
function setLanguageResolver(fn) { resolver = typeof fn === 'function' ? fn : vscodeLanguage; }

function language() {
  let value;
  try { value = resolver(); } catch (_) { value = 'en'; }
  return value === 'pt-BR' ? 'pt-BR' : 'en';
}

function format(text, params) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (params[name] === undefined || params[name] === null ? match : String(params[name])));
}

function t(key, params) {
  const lang = language();
  const text = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key;
  return format(text, params);
}

// For inline <script> blocks of webviews: returns the source of
//   const L = {...}; const tr = (key, params) => ...;
// with every key that starts with one of the given prefixes (or exactly
// matches one of the given keys), in the active language. Safe to embed in HTML.
function webviewTranslator(prefixes) {
  const list = Array.isArray(prefixes) ? prefixes : [prefixes];
  const strings = {};
  for (const key of Object.keys(dictionaries.en)) {
    if (list.some(prefix => key === prefix || (prefix.endsWith('.') && key.startsWith(prefix)))) strings[key] = t(key);
  }
  const json = JSON.stringify(strings)
    .replace(/</g, '\\u003c').replace(/>/g, '\\u003e').replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  return `const L=${json};const tr=(k,p)=>(L[k]===undefined?k:L[k]).replace(/\\{(\\w+)\\}/g,(m,n)=>p&&p[n]!==undefined&&p[n]!==null?String(p[n]):m);`;
}

// Environment for child processes: python/bash scripts read HPLC_LANG.
function languageEnv() { return { HPLC_LANG: language() }; }

module.exports = { t, language, resolveLanguage, setLanguageResolver, webviewTranslator, languageEnv, dictionaries };
