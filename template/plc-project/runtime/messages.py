MESSAGES = {"en": EN, "pt-BR": PT_BR}


def language():
    """'pt-BR' when HPLC_LANG asks for Portuguese, otherwise 'en'."""
    value = os.environ.get("HPLC_LANG", "").strip().lower().replace("_", "-")
    return "pt-BR" if value.startswith("pt") else "en"


def msg(key, **params):
    text = MESSAGES[language()].get(key) or EN[key]
    return text.format(**params) if params else text
